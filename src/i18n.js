// Idioma de la interfaz y del contenido.
let lang = 'es';

export const LANGS = [
  { id: 'es', name: 'Español' },
  { id: 'en', name: 'English' },
];

export const getLang = () => lang;
export function setLang(l) {
  lang = LANGS.some((x) => x.id === l) ? l : 'es';
  document.documentElement.lang = lang;
}

/** Texto localizado: string tal cual, u objeto {es, en}. */
export function loc(v) {
  if (v == null) return '';
  if (typeof v === 'string') return v;
  if (typeof v === 'object') return v[lang] ?? v.en ?? v.es ?? Object.values(v)[0] ?? '';
  return String(v);
}

